/**
 * attribution-entrypoints.test.ts — every way text enters the repo strips AI
 * attribution (AGENTS.md rule 6). Fixtures contain the forbidden phrases on
 * purpose; this file is on the guard's allowlist.
 */

import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DEFAULT_CONFIG } from "../src/config";
import { addComment, listComments } from "../src/lib/comments";
import { createGitHubClient } from "../src/lib/sync/github-client";
import { pullFromGitHub } from "../src/lib/sync/pull";
import { pushToGitHub, syncStatus } from "../src/lib/sync/push";
import { readAttributionTrip } from "../src/lib/sync/attribution-breaker";
import { parseCommentBody, renderCommentBody, parseIssueToTask } from "../src/lib/sync/render";
import { createBlankTask, loadTasks, saveTaskToStore } from "../src/lib/tasks";
import { startFakeGitHub, type FakeGitHub } from "./helpers/fake-github";
import { makeRepo } from "./helpers/git-repo";

const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";

let root: string;
let fake: FakeGitHub;
beforeEach(() => {
  root = makeRepo();
  saveTaskToStore(root, DEFAULT_CONFIG, createBlankTask("t1", "Task one"));
  fake = startFakeGitHub({ token: "tok" });
});
afterEach(() => {
  fake.stop();
  rmSync(root, { recursive: true, force: true });
});

const allFilesText = (dir: string): string => {
  let out = "";
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    out += e.isDirectory() ? allFilesText(p) : readFileSync(p, "utf-8");
  }
  return out;
};

describe("attribution never enters the repo", () => {
  test("addComment strips a footer from the stored body", () => {
    const c = addComment(root, { kind: "task", id: "t1" }, { body: `Handoff notes${FOOTER}`, author: "bob" });
    expect(c.body).toBe("Handoff notes");
    expect(listComments(root, { kind: "task", id: "t1" })[0]!.body).toBe("Handoff notes");
    expect(allFilesText(join(root, ".wombo-combo", "comments"))).not.toMatch(/claude\.ai|Generated by/i);
  });

  test("addComment rejects a body that is only attribution", () => {
    expect(() => addComment(root, { kind: "task", id: "t1" }, { body: "_Generated by Claude Code_" })).toThrow(/empty/);
  });

  test("renderCommentBody never sends attribution out", () => {
    const out = renderCommentBody({ id: "c1", author: "bob", role: "human", body: `hello${FOOTER}` });
    expect(out).not.toMatch(/claude\.ai|Generated by/i);
  });

  test("parseCommentBody and parseIssueToTask drop footers added on the GitHub side", () => {
    expect(parseCommentBody(`Looks good${FOOTER}`).body).toBe("Looks good");
    const parsed = parseIssueToTask({
      number: 9, url: "u", title: "Fix it", body: `Do the thing${FOOTER}`, state: "open", stateReason: null,
      labels: [], updatedAt: "2026-01-01T00:00:00Z", user: "x",
    } as never);
    expect(parsed.description).toBe("Do the thing");
  });

  test("pulling a GitHub comment and a GitHub issue stores no attribution", async () => {
    fake.seedIssue({ title: "From GitHub", body: `Please do X.${FOOTER}` });
    fake.seedComment(1, `Nice work${FOOTER}`, { user: { login: "octocat" } });
    const client = createGitHubClient({ token: "tok", repo: { owner: fake.owner, name: fake.repo }, apiUrl: fake.url, sleep: async () => {} });
    await pullFromGitHub({ projectRoot: root, client });
    const task = loadTasks(root, DEFAULT_CONFIG).tasks.find((t) => t.id.startsWith("gh-1-"))!;
    expect(task.description).toBe("Please do X.");
    const cs = listComments(root, { kind: "task", id: task.id });
    expect(cs.map((c) => c.body)).toEqual(["Nice work"]);
    expect(allFilesText(join(root, ".wombo-combo"))).not.toMatch(/claude\.ai|Generated by \[?Claude/i);
  });
});

describe("circuit breaker: a host that appends a footer to writes", () => {
  const clientFor = () => createGitHubClient({ token: "tok", repo: { owner: fake.owner, name: fake.repo }, apiUrl: fake.url, sleep: async () => {} });
  const writes = () => fake.requests.filter((r) => r.method !== "GET" && !/labels/.test(r.path));

  beforeEach(() => {
    fake.stop();
    fake = startFakeGitHub({ token: "tok", appendOnWrite: FOOTER });
    saveTaskToStore(root, DEFAULT_CONFIG, createBlankTask("t2", "Task two"));
  });

  test("trips after the first create: no scrub edit, no further writes, state recorded, error reported", async () => {
    const client = clientFor();
    const report = await pushToGitHub({ projectRoot: root, client });
    expect(report.attributionBreaker?.ref).toBe("t1");
    expect(report.errors.length).toBeGreaterThan(0);
    expect(report.created).toEqual([]);
    expect(fake.issues).toHaveLength(1); // t2 never created
    expect(writes().map((r) => r.method)).toEqual(["POST"]); // no loop-edit
    expect(readAttributionTrip(root)?.issue).toBe(1);

    const st = await syncStatus({ projectRoot: root, client });
    expect(st.attributionBreaker?.ref).toBe("t1");
  });

  test("trips on an update write too", async () => {
    fake.setAppendOnWrite("");
    const client = clientFor();
    expect((await pushToGitHub({ projectRoot: root, client })).errors).toEqual([]);
    fake.setAppendOnWrite(FOOTER);
    saveTaskToStore(root, DEFAULT_CONFIG, { ...createBlankTask("t1", "Task one"), description: "now with a description" });
    const again = await pushToGitHub({ projectRoot: root, client });
    expect(again.attributionBreaker?.ref).toBe("t1");
    expect(fake.requests.filter((r) => r.method === "PATCH")).toHaveLength(1);
    expect(fake.issues).toHaveLength(2);
  });

  test("trips on a mirrored comment and stops", async () => {
    fake.setAppendOnWrite("");
    const client = clientFor();
    await pushToGitHub({ projectRoot: root, client });
    fake.setAppendOnWrite(FOOTER);
    addComment(root, { kind: "task", id: "t1" }, { body: "hello", author: "bob" });
    const report = await pushToGitHub({ projectRoot: root, client });
    expect(report.attributionBreaker?.comment).toBeDefined();
    expect(fake.comments).toHaveLength(1);
    expect(fake.requests.filter((r) => r.method === "PATCH")).toHaveLength(0);
  });

  test("a clean host clears a recorded trip after a successful push", async () => {
    await pushToGitHub({ projectRoot: root, client: clientFor() });
    expect(readAttributionTrip(root)).not.toBeNull();
    fake.setAppendOnWrite("");
    const report = await pushToGitHub({ projectRoot: root, client: clientFor() });
    expect(report.errors).toEqual([]);
    expect(readAttributionTrip(root)).toBeNull();
  });
});

describe("a host that appends a footer only when text is read back", () => {
  const RAW = /claude\.ai|Generated by/i;
  const mkClient = () =>
    createGitHubClient({ token: "tok", repo: { owner: fake.owner, name: fake.repo }, apiUrl: fake.url, sleep: async () => {} });
  const readBodies = async (client: ReturnType<typeof mkClient>) => ({
    issue: (await client.getIssue(1)).body ?? "",
    comments: (await client.listComments(1)).map((c) => c.body),
  });

  test("create re-reads the new issue, trips the breaker and does not edit it", async () => {
    fake.stop();
    fake = startFakeGitHub({ token: "tok", appendOnRead: FOOTER });
    const client = mkClient();
    addComment(root, { kind: "task", id: "t1" }, { body: "hello from woco", author: "bob" });

    const report = await pushToGitHub({ projectRoot: root, client });
    expect(report.attributionBreaker?.ref).toBe("t1");
    expect(report.errors).toHaveLength(1);
    expect(fake.requests.filter((r) => r.method !== "GET" && !/labels/.test(r.path)).map((r) => r.method)).toEqual(["POST"]);
    expect(fake.comments).toHaveLength(0);
  });

  test("a later push cleans an issue and a comment that are already dirty, then sends no writes", async () => {
    const client = mkClient();
    addComment(root, { kind: "task", id: "t1" }, { body: "hello from woco", author: "bob" });
    expect((await pushToGitHub({ projectRoot: root, client })).errors).toEqual([]);
    // the host decorates what is already on GitHub
    fake.issues[0]!.body += FOOTER;
    fake.comments[0]!.body += FOOTER;
    expect((await readBodies(client)).issue).toMatch(RAW);

    const report = await pushToGitHub({ projectRoot: root, client });
    expect(report.errors).toEqual([]);
    const seen = await readBodies(client);
    expect(seen.issue).not.toMatch(RAW);
    expect(seen.comments[0]).not.toMatch(RAW);
    expect(seen.comments[0]).toContain("hello from woco");

    const before = fake.requests.length;
    const again = await pushToGitHub({ projectRoot: root, client });
    expect(again.errors).toEqual([]);
    expect(fake.requests.slice(before).filter((r) => r.method !== "GET")).toEqual([]);
  });

  test("an unmapped-but-existing dirty issue is cleaned too", async () => {
    const client = mkClient();
    expect((await pushToGitHub({ projectRoot: root, client })).errors).toEqual([]);
    fake.issues[0]!.body += FOOTER;
    rmSync(join(root, ".wombo-combo", "sync"), { recursive: true, force: true });
    expect((await pushToGitHub({ projectRoot: root, client })).errors).toEqual([]);
    expect((await readBodies(client)).issue).not.toMatch(RAW);
  });
});

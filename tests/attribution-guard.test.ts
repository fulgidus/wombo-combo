/**
 * attribution-guard.test.ts — the repo itself must contain no AI attribution
 * (AGENTS.md rule 6). Runs the same scan as CI (`scripts/check-attribution.ts`).
 */

import { describe, expect, test } from "bun:test";
import { scanText, scanTrackedFiles } from "../scripts/check-attribution";

describe("attribution guard", () => {
  test("no tracked file contains AI attribution", () => {
    expect(scanTrackedFiles()).toEqual([]);
  });

  test("scanText reports file, line and text", () => {
    const f = scanText("x.md", "ok\n_Generated by Claude Code_\nok");
    expect(f).toEqual([{ where: "x.md", line: 2, text: "_Generated by Claude Code_" }]);
  });
});

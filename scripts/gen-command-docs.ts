/**
 * gen-command-docs.ts — Generates the Starlight command reference from
 * COMMAND_REGISTRY (src/lib/schema.ts).
 *
 * Output (deterministic, no timestamps) goes to
 * docs/src/content/docs/reference/commands/: one `index.md` plus one page per
 * top-level command (subcommands are sections of their parent's page).
 *
 * Usage: bun scripts/gen-command-docs.ts   (or: bun run docs:gen)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { CommandDef, FlagDef } from "../src/lib/schema";
import { COMMAND_REGISTRY, GLOBAL_FLAGS, getCommandFlags } from "../src/lib/schema";

export const GENERATED_BANNER =
  "<!-- GENERATED by scripts/gen-command-docs.ts from COMMAND_REGISTRY. Do not edit by hand. -->";

/** Escape text for a Markdown table cell / paragraph. */
export function escapeCell(text: string): string {
  return text
    .replace(/\r?\n+/g, " ")
    .replace(/\|/g, "\\|")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/** File slug of a (possibly compound) command name: its top-level word. */
export function commandSlug(name: string): string {
  return name.split(" ")[0];
}

function code(value: string): string {
  return `\`${value}\``;
}

function formatDefault(value: unknown): string {
  return value === undefined ? "" : code(JSON.stringify(value));
}

function usageLine(cmd: CommandDef): string {
  const positionals = cmd.positionals.map((p) => (p.required ? `<${p.name}>` : `[${p.name}]`));
  const hasSubs = (cmd.subcommands?.length ?? 0) > 0;
  const parts = ["woco", cmd.name, ...(hasSubs ? ["<subcommand>"] : []), ...positionals, "[flags]"];
  return parts.join(" ");
}

function flagTable(flags: FlagDef[]): string[] {
  const lines = ["| Flag | Alias | Type | Default | Description |", "| --- | --- | --- | --- | --- |"];
  for (const f of flags) {
    const base = escapeCell(f.description);
    const desc = base +
      (f.enum ? `${/[.!?]$/.test(base) ? "" : "."} Values: ${f.enum.map(code).join(", ")}.` : "") +
      (f.required ? " **Required.**" : "");
    lines.push(
      `| ${code(f.name)} | ${f.alias ? code(f.alias) : ""} | ${f.type} | ${formatDefault(f.default)} | ${desc} |`,
    );
  }
  return lines;
}

/** Sections shared by a command and its subcommands. `level` is the heading depth. */
function commandBody(cmd: CommandDef, level: number): string[] {
  const h = "#".repeat(level);
  const out: string[] = [];
  out.push(escapeCell(cmd.summary), "");
  if (cmd.description && cmd.description !== cmd.summary) out.push(escapeCell(cmd.description), "");
  if (cmd.aliases?.length) out.push(`Aliases: ${cmd.aliases.map(code).join(", ")}`, "");
  out.push("```sh", usageLine(cmd), "```", "");
  const traits: string[] = [];
  traits.push(cmd.mutating ? "Modifies project state." : "Read-only.");
  if (cmd.supportsDryRun) traits.push("Supports `--dry-run`.");
  out.push(traits.join(" "), "");

  if (cmd.positionals.length) {
    out.push(`${h} Arguments`, "", "| Argument | Required | Description |", "| --- | --- | --- |");
    for (const p of cmd.positionals) {
      out.push(`| ${code(p.name)} | ${p.required ? "yes" : "no"} | ${escapeCell(p.description)} |`);
    }
    out.push("");
  }

  if (cmd.flags.length) {
    out.push(`${h} Flags`, "", ...flagTable(cmd.flags), "");
  }

  const own = new Set(cmd.flags.map((f) => f.name));
  const globals = getCommandFlags(cmd).filter((f) => !own.has(f.name));
  if (globals.length) {
    out.push(`${h} Global flags`, "", ...flagTable(globals), "");
  }
  return out;
}

export function renderCommandPage(cmd: CommandDef): string {
  const lines: string[] = [
    "---",
    `title: ${cmd.name}`,
    `description: ${JSON.stringify(cmd.summary)}`,
    "---",
    "",
    GENERATED_BANNER,
    "",
    ...commandBody(cmd, 2),
  ];
  for (const sub of cmd.subcommands ?? []) {
    lines.push(`## ${sub.name}`, "", ...commandBody(sub, 3));
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

export function renderIndexPage(commands: CommandDef[]): string {
  const lines: string[] = [
    "---",
    "title: Command reference",
    'description: "Every wombo-combo command, generated from the CLI\'s own command registry."',
    "---",
    "",
    GENERATED_BANNER,
    "",
    "Pages in this section are generated from the same registry that powers `woco describe` and shell completion,",
    "so they always match the CLI. Run `woco <command> --help` for the same information in your terminal.",
    "",
    "## Commands",
    "",
    "| Command | Summary |",
    "| --- | --- |",
  ];
  for (const cmd of commands) {
    lines.push(`| [${code(cmd.name)}](./${commandSlug(cmd.name)}/) | ${escapeCell(cmd.summary)} |`);
  }
  lines.push("", "## Global flags", "", "Available on every command unless the command defines a flag of the same name.", "");
  lines.push(...flagTable(GLOBAL_FLAGS), "");
  return lines.join("\n");
}

/** Relative file name -> content for the whole reference. */
export function generateCommandDocs(commands: CommandDef[]): Map<string, string> {
  const files = new Map<string, string>();
  files.set("index.md", renderIndexPage(commands));
  for (const cmd of commands) files.set(`${commandSlug(cmd.name)}.md`, renderCommandPage(cmd));
  return files;
}

/** Write the reference into `outDir`, deleting stale generated `.md` files. */
export function writeCommandDocs(outDir: string, commands: CommandDef[]): void {
  const files = generateCommandDocs(commands);
  mkdirSync(outDir, { recursive: true });
  for (const name of readdirSync(outDir)) {
    if (!name.endsWith(".md") || files.has(name)) continue;
    const path = join(outDir, name);
    if (readFileSync(path, "utf-8").includes(GENERATED_BANNER)) unlinkSync(path);
  }
  for (const [name, content] of files) {
    const path = join(outDir, name);
    if (!existsSync(path) || readFileSync(path, "utf-8") !== content) writeFileSync(path, content);
  }
}

if (import.meta.main) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const outDir = join(root, "docs/src/content/docs/reference/commands");
  writeCommandDocs(outDir, COMMAND_REGISTRY);
  console.log(`Wrote command reference (${COMMAND_REGISTRY.length} commands) to ${outDir}`);
}

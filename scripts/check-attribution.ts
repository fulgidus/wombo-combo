#!/usr/bin/env bun
/**
 * check-attribution.ts — fail when AI attribution is present (AGENTS.md rule 6).
 *
 * Usage:
 *   bun scripts/check-attribution.ts                    scan every tracked text file
 *   bun scripts/check-attribution.ts --message-file F   scan one commit message (commit-msg hook)
 *   bun scripts/check-attribution.ts --head             scan the HEAD commit message
 *   bun scripts/check-attribution.ts --range A..B       scan every commit message in a range
 *
 * Files that document or test the rule are allowlisted below.
 */

import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, readFileSync } from "node:fs";
import { lineHasAiAttribution } from "../src/lib/attribution";

/** Files that must mention the forbidden phrases (the rule itself, its detector and its tests). */
const ALLOWLIST: readonly RegExp[] = [
  /^AGENTS\.md$/,
  /^CLAUDE\.md$/,
  /^docs\/agents\/no-ai-attribution\.md$/,
  /^src\/lib\/attribution\.ts$/,
  /^scripts\/check-attribution\.ts$/,
  /^tests\/attribution[\w.-]*\.test\.ts$/,
];

const MAX_BYTES = 2 * 1024 * 1024;

export interface Finding {
  where: string;
  line: number;
  text: string;
}

export function scanText(where: string, text: string): Finding[] {
  const out: Finding[] = [];
  text.split(/\r?\n/).forEach((line, i) => {
    if (lineHasAiAttribution(line)) out.push({ where, line: i + 1, text: line.trim().slice(0, 140) });
  });
  return out;
}

function git(args: string[]): string {
  const r = spawnSync("git", args, { encoding: "utf-8", maxBuffer: 256 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${r.stderr}`);
  return r.stdout;
}

export function scanTrackedFiles(): Finding[] {
  const findings: Finding[] = [];
  for (const file of git(["ls-files", "-z"]).split("\0").filter(Boolean)) {
    if (ALLOWLIST.some((re) => re.test(file))) continue;
    if (!existsSync(file) || lstatSync(file).isSymbolicLink()) continue;
    const stat = lstatSync(file);
    if (!stat.isFile() || stat.size > MAX_BYTES) continue;
    const buf = readFileSync(file);
    if (buf.includes(0)) continue; // binary
    findings.push(...scanText(file, buf.toString("utf-8")));
  }
  return findings;
}

export function scanCommits(range: string): Finding[] {
  const findings: Finding[] = [];
  const log = git(["log", "--format=%H%x00%B%x01", range]);
  for (const rec of log.split("\x01")) {
    const [sha, body] = rec.replace(/^\n/, "").split("\0");
    if (sha && body) findings.push(...scanText(`commit ${sha.slice(0, 8)}`, body));
  }
  return findings;
}

function report(findings: Finding[]): never | void {
  if (findings.length === 0) return;
  console.error("AI attribution found. It is forbidden anywhere in this project (AGENTS.md rule 6):");
  for (const f of findings) console.error(`  ${f.where}:${f.line}: ${f.text}`);
  console.error("Remove it (and never add Co-Authored-By trailers, 'Generated by/with' footers or session links).");
  process.exit(1);
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const flag = (n: string) => args.indexOf(n);
  let findings: Finding[];
  if (flag("--message-file") >= 0) {
    const file = args[flag("--message-file") + 1];
    findings = scanText("commit message", readFileSync(file, "utf-8"));
  } else if (flag("--head") >= 0) {
    findings = scanCommits("-1");
  } else if (flag("--range") >= 0) {
    findings = scanCommits(args[flag("--range") + 1]);
  } else {
    findings = scanTrackedFiles();
  }
  report(findings);
  console.log("No AI attribution found.");
}
